// 龙娘用固定短句回应互动和任务事件，不调用模型，也不消耗账户额度。
const DIALOGUE = {
  chat: [
    '在呢，GPT 龙娘待命！\n把想法交给我，我们一步一步来。',
    '龙角收到信号啦！\n想继续攻克难题，还是先聊个新点子？',
    '我在旁边守着呢。\n复杂的事拆小一点，就又能往前走一步啦。',
    '被你发现我在待命啦。\n下一站想做什么？我们一起把它变成现实。',
    '尾巴晃一晃，灵感来报到！\n有新想法就说，我陪你一起琢磨。',
  ],
  complete: [
    '叮，交卷啦！这轮任务完成了，快来看看结果吧。',
    '龙角亮一下，这一轮搞定啦！下一步想做什么，我继续陪你。',
    '收到，任务完成！成果已经等着你啦，过来看看吧。',
  ],
  cancelled: ['好，这一轮先停在这里。等你想继续时，再叫我出发吧。'],
  error: ['这一轮遇到一点阻碍。来看看提示，我们一起把问题拆开解决。'],
};

// 按事件独立轮换，连续点“说句话”总能得到下一句回应。
export function dialogueLine(kind, index = 0) {
  const lines = DIALOGUE[kind] || DIALOGUE.chat;
  return lines[Math.abs(index) % lines.length];
}
